STATUS_COL = "K"
DEFAULT_STATUS = "Not Run"
DEFAULT_AUTOMATION = "—"
DEFAULT_METHOD = "UI"


def read_existing_results(path: Path) -> dict:
    """Вычитывает из существующего файла заполненные вручную колонки.

    Колонки ищутся по заголовкам (а не по буквам), поэтому сохранение
    работает, даже если состав колонок между версиями скрипта менялся.
    Возвращает {ID кейса: (фактический результат, статус)}.
    """
    results: dict[str, tuple] = {}
    if not path.exists():
        return results
    wb = openpyxl.load_workbook(path, read_only=True, data_only=False)
    for ws in wb.worksheets:
        if ws.title == SUMMARY_SHEET:
            continue
        header = next(ws.iter_rows(min_row=1, max_row=1, values_only=True), None)
        if not header:
            continue
        try:
            fact_idx = header.index("Фактический результат")
            status_idx = header.index("Статус")
        except ValueError:
            continue
        for row in ws.iter_rows(min_row=2, values_only=True):
            if not row or not row[0]:
                continue
            case_id = str(row[0]).strip()
            if not case_id.startswith("TC-"):
                continue
            fact = row[fact_idx] if len(row) > fact_idx else None
            status = row[status_idx] if len(row) > status_idx else None
            results[case_id] = (fact, status)
    wb.close()
    return results


def build_module_sheet(wb, module, preserved):
    ws = wb.create_sheet(module["sheet"])

    # Заголовки
    for col_idx, (header, width) in enumerate(COLUMNS, start=1):
        cell = ws.cell(row=1, column=col_idx, value=header)
        cell.font = HEADER_FONT
        cell.fill = HEADER_FILL
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        ws.column_dimensions[get_column_letter(col_idx)].width = width
    ws.row_dimensions[1].height = 28

    wrap = Alignment(vertical="top", wrap_text=True)
    center = Alignment(horizontal="center", vertical="top")

    for row_idx, case in enumerate(module["cases"], start=2):
        steps_text = "\n".join(f"{i}. {s}" for i, s in enumerate(case["steps"], start=1))
        fact_saved, status_saved = preserved.get(case["id"], (None, None))

        values = [
            case["id"],
            case["title"],
            case["desc"],
            case["pre"],
            steps_text,
            case["priority"],
            case["ctype"],
            case.get("method", DEFAULT_METHOD),
            case["expected"],
            fact_saved or "",
            status_saved or DEFAULT_STATUS,
            DEFAULT_AUTOMATION,
        ]
        for col_idx, value in enumerate(values, start=1):
            cell = ws.cell(row=row_idx, column=col_idx, value=value)
            cell.border = THIN_BORDER
            if col_idx in (1, 6, 7, 8, 11, 12):  # ID, Приоритет, Тип, Способ, Статус, Автоматизация
                cell.alignment = center
            else:
                cell.alignment = wrap

        # Примерная высота строки: по самой «высокой» ячейке
        def est_lines(text, width_chars):
            lines = 0
            for part in str(text).split("\n"):
                lines += max(1, (len(part) // width_chars) + 1)
            return lines

        n_lines = max(
            est_lines(steps_text, 55),
            est_lines(case["desc"], 40),
            est_lines(case["expected"], 44),
            est_lines(case["pre"], 30),
        )
        ws.row_dimensions[row_idx].height = min(max(n_lines * 13.2 + 4, 30), 300)

    last_row = len(module["cases"]) + 1

    # Выпадающие списки (с запасом на 30 строк ниже — если кейсы добавятся руками)
    dv_priority = DataValidation(type="list", formula1=PRIORITY_LIST, allow_blank=True)
    dv_priority.error = "Выбери значение из списка: Critical, High, Medium, Low"
    dv_priority.errorTitle = "Недопустимое значение"
    ws.add_data_validation(dv_priority)
    dv_priority.add(f"F2:F{last_row + 30}")

    dv_status = DataValidation(type="list", formula1=STATUS_LIST, allow_blank=True)
    dv_status.error = "Выбери значение из списка: Not Run, Passed, Failed, Blocked"
    dv_status.errorTitle = "Недопустимое значение"
    ws.add_data_validation(dv_status)
    dv_status.add(f"{STATUS_COL}2:{STATUS_COL}{last_row + 30}")

    dv_method = DataValidation(type="list", formula1=METHOD_LIST, allow_blank=True)
    dv_method.error = "Выбери значение из списка: UI, API, UI+API"
    dv_method.errorTitle = "Недопустимое значение"
    ws.add_data_validation(dv_method)
    dv_method.add(f"H2:H{last_row + 30}")

    # Условное форматирование статуса
    status_range = f"{STATUS_COL}2:{STATUS_COL}{last_row + 30}"
    for status, (bg, fg) in STATUS_COLORS.items():
        ws.conditional_formatting.add(
            status_range,
            CellIsRule(
                operator="equal",
                formula=[f'"{status}"'],
                fill=PatternFill("solid", fgColor=bg),
                font=Font(color=fg, bold=(status in ("Passed", "Failed"))),
            ),
        )

    # Закрепление шапки и автофильтр
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:{get_column_letter(len(COLUMNS))}{last_row}"

    return ws


def build_summary(wb):
    ws = wb.create_sheet(SUMMARY_SHEET, 0)

    ws.column_dimensions["A"].width = 34
    for col in "BCDEFG":
        ws.column_dimensions[col].width = 12

    title = ws.cell(row=1, column=1, value="Operator AI — тест-кейсы ручного тестирования")
    title.font = Font(bold=True, size=14, color="2247C9")
    note = ws.cell(
        row=2,
        column=1,
        value="Как пользоваться: открой лист модуля, выполни шаги кейса на тестовом стенде, "
              "запиши «Фактический результат» и поставь «Статус» из выпадающего списка. "
              "Сводка ниже пересчитается сама.",
    )
    note.font = Font(italic=True, size=10, color="595959")
    note.alignment = Alignment(wrap_text=True, vertical="top")
    ws.merge_cells("A2:G2")
    ws.row_dimensions[2].height = 40
    warn = ws.cell(
        row=3,
        column=1,
        value="Все проверки — только на тестовом стенде (staging). Учётные данные и токены — в .env, "
              "в этот файл их не вписываем. Названия кнопок даны по-русски, в скобках — узбекский "
              "вариант интерфейса. Колонка «Способ проверки»: UI — через браузер, API — запросом "
              "(curl/Postman, команда дана в шагах), UI+API — комбинированно. {STAGE_API_URL} в командах "
              "замени на адрес бэкенда тестового стенда из .env.",
    )
    warn.font = Font(italic=True, size=10, color="9C0006")
    warn.alignment = Alignment(wrap_text=True, vertical="top")
    ws.merge_cells("A3:G3")
    ws.row_dimensions[3].height = 40

    header_row = 5
    headers = ["Модуль", "Кейсов", "Passed", "Failed", "Blocked", "Not Run", "% пройдено"]
    for col_idx, header in enumerate(headers, start=1):
        cell = ws.cell(row=header_row, column=col_idx, value=header)
        cell.font = HEADER_FONT
        cell.fill = HEADER_FILL
        cell.alignment = Alignment(horizontal="center", vertical="center")

    main_modules = [m for m in MODULES if not m["sheet"].startswith(DEFERRED_SHEET_PREFIX)]
    deferred_modules = [m for m in MODULES if m["sheet"].startswith(DEFERRED_SHEET_PREFIX)]

    row = header_row + 1
    first_data_row = row
    for module in main_modules:
        sheet = module["sheet"]
        n = len(module["cases"])
        ref = f"'{sheet}'!${STATUS_COL}$2:${STATUS_COL}${n + 1}"
        ws.cell(row=row, column=1, value=sheet)
        ws.cell(row=row, column=2, value=n)
        ws.cell(row=row, column=3, value=f'=COUNTIF({ref},"Passed")')
        ws.cell(row=row, column=4, value=f'=COUNTIF({ref},"Failed")')
        ws.cell(row=row, column=5, value=f'=COUNTIF({ref},"Blocked")')
        ws.cell(row=row, column=6, value=f'=COUNTIF({ref},"Not Run")')
        pct = ws.cell(row=row, column=7, value=f"=IF(B{row}=0,0,C{row}/B{row})")
        pct.number_format = "0%"
        for col_idx in range(1, 8):
            ws.cell(row=row, column=col_idx).border = THIN_BORDER
        row += 1

    total_row = row
    ws.cell(row=total_row, column=1, value="ИТОГО (без отложенных)").font = Font(bold=True)
    for col_idx, letter in ((2, "B"), (3, "C"), (4, "D"), (5, "E"), (6, "F")):
        c = ws.cell(
            row=total_row,
            column=col_idx,
            value=f"=SUM({letter}{first_data_row}:{letter}{total_row - 1})",
        )
        c.font = Font(bold=True)
    pct = ws.cell(row=total_row, column=7, value=f"=IF(B{total_row}=0,0,C{total_row}/B{total_row})")
    pct.number_format = "0%"
    pct.font = Font(bold=True)
    for col_idx in range(1, 8):
        ws.cell(row=total_row, column=col_idx).border = THIN_BORDER
        ws.cell(row=total_row, column=col_idx).fill = PatternFill("solid", fgColor="E8EDFB")

    # Отложенные — отдельной строкой, вне общего процента
    if deferred_modules:
        row = total_row + 2
        label = ws.cell(row=row, column=1, value="Вне общей статистики (ждут релиза):")
        label.font = Font(italic=True, size=10, color="595959")
        row += 1
        for module in deferred_modules:
            sheet = module["sheet"]
            n = len(module["cases"])
            ref = f"'{sheet}'!${STATUS_COL}$2:${STATUS_COL}${n + 1}"
            ws.cell(row=row, column=1, value=sheet)
            ws.cell(row=row, column=2, value=n)
            ws.cell(row=row, column=3, value=f'=COUNTIF({ref},"Passed")')
            ws.cell(row=row, column=4, value=f'=COUNTIF({ref},"Failed")')
            ws.cell(row=row, column=5, value=f'=COUNTIF({ref},"Blocked")')
            ws.cell(row=row, column=6, value=f'=COUNTIF({ref},"Not Run")')
            ws.cell(row=row, column=7, value="—").alignment = Alignment(horizontal="center")
            for col_idx in range(1, 8):
                ws.cell(row=row, column=col_idx).border = THIN_BORDER
                ws.cell(row=row, column=col_idx).font = Font(italic=True, color="595959")
            row += 1

    return ws


def main():
    preserved = read_existing_results(TARGET_FILE)
    if preserved:
        filled = sum(1 for fact, status in preserved.values()
                     if (fact and str(fact).strip()) or (status and str(status).strip() not in ("", DEFAULT_STATUS)))
        print(f"Найден существующий файл: сохранено ручных результатов — {filled} "
              f"(всего кейсов в старом файле: {len(preserved)})")

    wb = openpyxl.Workbook()
    wb.remove(wb.active)  # убираем пустой лист по умолчанию

    for module in MODULES:
        build_module_sheet(wb, module, preserved)

    build_summary(wb)

    # Проверка сквозной нумерации и уникальности ID
    seen = set()
    for module in MODULES:
        for case in module["cases"]:
            assert case["id"] not in seen, f"Дубль ID: {case['id']}"
            seen.add(case["id"])

    wb.save(TARGET_FILE)
    total = sum(len(m["cases"]) for m in MODULES)
    print(f"Готово: {TARGET_FILE}")
    print(f"Листов-модулей: {len(MODULES)}, кейсов всего: {total}")


if __name__ == "__main__":
    main()
